import { chromium, expect } from '@playwright/test';
const browser = await chromium.launch();
try {
  const page = await browser.newPage({viewport:{width:1600,height:1200},reducedMotion:'reduce'});
  const visit = route => page.goto('http://127.0.0.1:4173/neural-atlas/#/'+route);
  await visit('lab/experimentos');
  await page.getByLabel('Épocas comunes',{exact:true}).fill('15');
  await page.getByLabel('Capas ocultas A',{exact:true}).fill('');
  await page.getByRole('button',{name:'Ejecutar estudio',exact:true}).click();
  await expect(page.getByRole('table',{name:'Resultados de experimentos A/B',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Activar vista de proyección A/B',exact:true}).click();
  await page.locator('.projection-comparison').screenshot({path:'docs/implementation/d7-projection.png'});
  await visit('lab/experimentos/robustez');
  await page.getByLabel('Épocas por semilla',{exact:true}).fill('5');
  await page.getByRole('button',{name:'Ejecutar estudio de robustez',exact:true}).click();
  await expect(page.getByRole('table',{name:'Dispersión de predicciones',exact:true})).toBeVisible();
  await page.locator('section.training-panel').filter({has:page.getByRole('heading',{name:'Una misma fila, distintas semillas',exact:true})}).screenshot({path:'docs/implementation/d7-dispersion.png'});
  await page.getByRole('combobox',{name:'Estudio de robustez',exact:true}).selectOption('shift');
  await page.getByRole('combobox',{name:'Escenario de deriva',exact:true}).selectOption('concept');
  await page.getByRole('slider',{name:/Intensidad de deriva/}).fill('1');
  await page.getByLabel('Épocas antes de la deriva',{exact:true}).fill('15');
  await page.getByRole('button',{name:'Ejecutar estudio de robustez',exact:true}).click();
  await expect(page.getByRole('table',{name:'Resultados de deriva',exact:true})).toBeVisible();
  await page.locator('section.training-panel').filter({has:page.getByRole('heading',{name:'El mismo modelo ante datos distintos',exact:true})}).screenshot({path:'docs/implementation/d7-concept-drift.png'});
  await page.setViewportSize({width:390,height:900});
  await page.evaluate(()=>document.documentElement.setAttribute('data-theme','dark'));
  await page.locator('.shift-maps').evaluate(el=>el.scrollIntoView({block:'start',behavior:'instant'}));
  await page.screenshot({path:'docs/implementation/d7-drift-mobile.png'});
  await page.setViewportSize({width:1600,height:1200});
  await page.evaluate(()=>document.documentElement.setAttribute('data-theme','light'));
  await visit('lab/entrenamiento');
  await page.getByRole('combobox',{name:'Ejemplo de entrenamiento',exact:true}).selectOption('moons');
  await page.getByRole('button',{name:'Cargar ejemplo y sustituir datos',exact:true}).click();
  await page.getByLabel('Épocas máximas',{exact:true}).fill('8');
  await page.getByRole('button',{name:'Inicializar modelo',exact:true}).click();
  await expect(page.getByRole('button',{name:'Una época',exact:true})).toBeEnabled();
  await page.getByRole('button',{name:'Una época',exact:true}).click();
  await expect(page.locator('.training-status')).toContainText('Época 1');
  await page.getByRole('combobox',{name:'Optimizador del segmento',exact:true}).selectOption('momentum');
  await page.getByLabel('Tasa del segmento',{exact:true}).fill('0.02');
  await page.getByRole('button',{name:'Registrar segmento',exact:true}).click();
  await expect(page.getByRole('table',{name:'Segmentos registrados',exact:true}).locator('tbody tr')).toHaveCount(2);
  await expect(page.getByRole('button',{name:'Una época',exact:true})).toBeEnabled();
  await page.getByRole('button',{name:'Una época',exact:true}).click();
  await expect(page.locator('.training-status')).toContainText('Época 2');
  await page.getByRole('combobox',{name:'Optimizador del segmento',exact:true}).selectOption('adam');
  await page.getByLabel('Reiniciar también los pesos',{exact:false}).check();
  await page.getByRole('button',{name:'Registrar segmento',exact:true}).click();
  await expect(page.getByRole('table',{name:'Segmentos registrados',exact:true}).locator('tbody tr')).toHaveCount(3);
  await expect(page.getByRole('button',{name:'Una época',exact:true})).toBeEnabled();
  await page.getByRole('button',{name:'Una época',exact:true}).click();
  await expect(page.locator('.training-status')).toContainText('Época 3');
  await page.locator('.segment-panel').screenshot({path:'docs/implementation/d7-segments.png'});
  await page.locator('.loss-chart').screenshot({path:'docs/implementation/d7-segment-curves.png'});
} finally { await browser.close(); }
